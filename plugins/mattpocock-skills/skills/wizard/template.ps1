$script:TotalStages = 0
$script:StageIndex = 0
$script:EnvFile = if ($env:ENV_FILE) { $env:ENV_FILE } else { '.env' }
$script:WrittenEnv = [System.Collections.Generic.List[string]]::new()
$script:WrittenSecret = [System.Collections.Generic.List[string]]::new()
$script:Skipped = [System.Collections.Generic.List[string]]::new()

function Clear-WizardScreen {
  if ($Host.UI -and $Host.UI.RawUI) {
    try { Clear-Host } catch {}
  }
}

function Show-Banner {
  param([Parameter(Mandatory)][string]$Title)
  Clear-WizardScreen
  Write-Host ""
  Write-Host "  $Title" -ForegroundColor Cyan
  Write-Host "  $($script:TotalStages) stages" -ForegroundColor DarkGray
  Write-Host ""
  Write-Host "  You drive the browser; this wizard tells you exactly what to do and" -ForegroundColor DarkGray
  Write-Host "  captures the values you copy back. Stop any time with Ctrl-C and re-run" -ForegroundColor DarkGray
  Write-Host "  later, since it remembers values already saved." -ForegroundColor DarkGray
  Wait-Pause "Ready to start? (Press Enter)"
}

function Start-Stage {
  param([Parameter(Mandatory)][string]$Name)
  Clear-WizardScreen
  $script:StageIndex++
  Write-Host ""
  Write-Host "▸ Stage $($script:StageIndex)/$($script:TotalStages) · $Name" -ForegroundColor Cyan
}

function Write-Say  { param([string]$Text) Write-Host "  $Text" }
function Write-Step { param([string]$Text) Write-Host "  • " -ForegroundColor Cyan -NoNewline; Write-Host $Text }
function Write-Note { param([string]$Text) Write-Host "  $Text" -ForegroundColor DarkGray }
function Write-Warn { param([string]$Text) Write-Host "  ⚠ $Text" -ForegroundColor Yellow }

function Open-Url {
  param([Parameter(Mandatory)][string]$Url)
  Write-Host "  ↗ opening " -ForegroundColor Green -NoNewline
  Write-Host $Url
  try {
    Start-Process $Url | Out-Null
  } catch {
    Write-Warn "couldn't open a browser, so visit it manually: $Url"
  }
}

function Wait-Pause {
  param([string]$Message = 'Press Enter to continue')
  Write-Host "  $Message " -ForegroundColor DarkGray -NoNewline
  $null = Read-Host
}

function Confirm-Action {
  param([Parameter(Mandatory)][string]$Question)
  Write-Host "  ? $Question [y/N] " -ForegroundColor Yellow -NoNewline
  $reply = Read-Host
  return ($reply -match '^[Yy]')
}

function Get-ExistingEnvValue {
  param([Parameter(Mandatory)][string]$Key)
  if (-not (Test-Path -LiteralPath $script:EnvFile)) { return $null }
  $pattern = "^$([regex]::Escape($Key))="
  $lines = Get-Content -LiteralPath $script:EnvFile -ErrorAction SilentlyContinue | Where-Object { $_ -match $pattern }
  if (-not $lines) { return $null }
  $line = @($lines)[-1]
  $val = $line.Substring($Key.Length + 1)
  if ($val.StartsWith("'") -and $val.EndsWith("'") -and $val.Length -ge 2) {
    return $val.Substring(1, $val.Length - 2).Replace("'\''", "'")
  }
  if ($val.StartsWith('"') -and $val.EndsWith('"') -and $val.Length -ge 2) {
    $inner = $val.Substring(1, $val.Length - 2)
    if ($inner -match '[\\$"]') { return $null }
    return $inner
  }
  return $val
}

function Read-Value {
  param(
    [Parameter(Mandatory)][string]$Key,
    [Parameter(Mandatory)][string]$Prompt
  )
  $current = Get-ExistingEnvValue -Key $Key
  $suffix = if ($current) { " [Enter keeps current]" } else { "" }
  Write-Host "  $Prompt" -ForegroundColor White -NoNewline
  if ($suffix) { Write-Host $suffix -ForegroundColor DarkGray -NoNewline }
  Write-Host " " -NoNewline
  $inputVal = Read-Host
  if ([string]::IsNullOrEmpty($inputVal) -and $current) { return $current }
  return $inputVal
}

function Read-SecretValue {
  param(
    [Parameter(Mandatory)][string]$Key,
    [Parameter(Mandatory)][string]$Prompt
  )
  $current = Get-ExistingEnvValue -Key $Key
  $suffix = if ($current) { " [Enter keeps current]" } else { "" }
  Write-Host "  $Prompt" -ForegroundColor White -NoNewline
  if ($suffix) { Write-Host $suffix -ForegroundColor DarkGray -NoNewline }
  Write-Host " " -NoNewline
  $secure = Read-Host -AsSecureString
  $bstr = [System.Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
  try {
    $plain = [System.Runtime.InteropServices.Marshal]::PtrToStringAuto($bstr)
  } finally {
    [System.Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr)
  }
  if ([string]::IsNullOrEmpty($plain) -and $current) { return $current }
  return $plain
}

function Write-EnvValue {
  param(
    [Parameter(Mandatory)][string]$Key,
    [Parameter(Mandatory)][AllowEmptyString()][string]$Value
  )
  $existing = @()
  if (Test-Path -LiteralPath $script:EnvFile) {
    $pattern = "^$([regex]::Escape($Key))="
    $existing = @(Get-Content -LiteralPath $script:EnvFile -ErrorAction SilentlyContinue | Where-Object { $_ -notmatch $pattern })
  }
  $escaped = $Value.Replace("'", "'\''")
  $updated = $existing + "$Key='$escaped'"
  $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
  $targetPath = [System.IO.Path]::GetFullPath((Join-Path (Get-Location).Path $script:EnvFile))
  [System.IO.File]::WriteAllLines($targetPath, $updated, $utf8NoBom)
  $script:WrittenEnv.Add($Key)
  Write-Host "  ✓ wrote " -ForegroundColor Green -NoNewline
  Write-Host "$Key → $($script:EnvFile)"
}

function Set-GitHubSecret {
  param(
    [Parameter(Mandatory)][string]$Name,
    [Parameter(Mandatory)][string]$Value
  )
  if (Get-Command gh -ErrorAction SilentlyContinue) {
    $null = & gh auth status 2>$null
    if ($LASTEXITCODE -eq 0) {
      $Value | & gh secret set $Name 2>$null
      if ($LASTEXITCODE -eq 0) {
        $script:WrittenSecret.Add($Name)
        Write-Host "  ✓ set " -ForegroundColor Green -NoNewline
        Write-Host "GitHub secret $Name"
        return
      }
    }
  }
  $script:Skipped.Add("GitHub secret $Name (set it manually: gh secret set $Name)")
  Write-Warn "skipped GitHub secret ${Name}: gh not ready; set it later"
}

function Set-GitHubVar {
  param(
    [Parameter(Mandatory)][string]$Name,
    [Parameter(Mandatory)][string]$Value
  )
  if (Get-Command gh -ErrorAction SilentlyContinue) {
    $null = & gh auth status 2>$null
    if ($LASTEXITCODE -eq 0) {
      & gh variable set $Name --body $Value 2>$null
      if ($LASTEXITCODE -eq 0) {
        Write-Host "  ✓ set " -ForegroundColor Green -NoNewline
        Write-Host "GitHub variable $Name"
        return
      }
    }
  }
  $script:Skipped.Add("GitHub variable $Name")
  Write-Warn "skipped GitHub variable ${Name}: gh not ready; set it later"
}

function Complete-Wizard {
  Clear-WizardScreen
  Write-Host ""
  Write-Host "  ✓ Setup complete" -ForegroundColor Green
  if ($script:WrittenEnv.Count -gt 0) {
    Write-Note "wrote $($script:WrittenEnv.Count) value(s) to $($script:EnvFile): $($script:WrittenEnv -join ', ')"
  }
  if ($script:WrittenSecret.Count -gt 0) {
    Write-Note "set $($script:WrittenSecret.Count) GitHub secret(s): $($script:WrittenSecret -join ', ')"
  }
  if ($script:Skipped.Count -gt 0) {
    Write-Host ""
    Write-Warn "still to do by hand:"
    foreach ($s in $script:Skipped) { Write-Note "  - $s" }
  }
  Write-Host ""
}

